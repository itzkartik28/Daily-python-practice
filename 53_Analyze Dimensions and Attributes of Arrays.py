import numpy as np

arr=np.array([[10,20,30],
              [40,50,60]])

print("array:")
print(arr)

print("shape of array:")
print(arr.shape)

print("number of dimension:")
print(arr.ndim)

print("size of array:")
print(arr.size)

print("data type:")
print(arr.dtype)

print("item size:")
print(arr.itemsize)

print("total bytes:")
print(arr.ndytes)